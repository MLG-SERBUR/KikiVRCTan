        ("es", "Español", "🇪🇸"),
    ];

    // The user's Windows display language, when it is one we translate.
    public static string DetectSystem()
    {
        var code = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
        return Supported.Any(l => l.Code == code) ? code : "en";
    }

    // A saved choice wins; "" (never chosen) follows the system.
    public static string Resolve(string? saved)
    {
        if (!string.IsNullOrEmpty(saved) && Supported.Any(l => l.Code == saved)) return saved;
        return DetectSystem();
    }

    public static string NativeName(string code)
        => Supported.FirstOrDefault(l => l.Code == code).NativeName ?? "English";

    public static string Flag(string code)
        => Supported.FirstOrDefault(l => l.Code == code).Flag ?? "";

    // First-run source language for a UI language. The Source list has no
    // plain "es" (Spanish is regional there), so Spanish gets es-ES.
    public static string MapToSource(string uiCode)
    {
        var code = uiCode == "es" ? "es-ES" : uiCode;
        return Languages.Source.Any(l => l.Code == code) ? code : "en";
    }

    public static string T(string lang, string key)
    {
        if (Strings.TryGetValue(lang, out var table) && table.TryGetValue(key, out var value)) return value;
        if (lang != "en" && Strings["en"].TryGetValue(key, out var en)) return en;
        return key;
    }

